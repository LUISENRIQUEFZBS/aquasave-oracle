/**
 * Generates the response letter / sworn declaration PDF. The templates are PROVISIONAL placeholders (the PDF says so)
 * until the real wording is supplied. Every generation is kept (never overwritten).
 */
export async function generateDocument(dossierId: number, type: number) {
  return attempt(async () => {
    const s = await requireInternal();
    const dossier = await loadDossier(dossierId, true);
    const meta = GENERATED_META[type];
    if (!meta) throw new Error("Tipo de documento inválido.");
    const db = await getDb();
    const [client, site, sedapalLogo, saverLogo] = await Promise.all([
      db.getRepository(Client).findOne({ where: { id: dossier.clientId } }),
      db.getRepository(Site).findOne({ where: { id: dossier.siteId } }),
      loadSedapalLogo(),
      loadSaverLogo(),
    ]);
    if (!client || !site) throw new Error("Cliente o sede no encontrados.");
    const d: LetterPdfData = {
      isDraft: true,
      sedapalLogo,
      saverLogo,
      titleLines: meta.titleLines,
      generatedAt: new Date(),
      fileCode: dossier.code,
      client: { businessName: client.businessName, address: site.address },
      bodyParagraphs: meta.body,
      signatureLabel: meta.signatureLabel,
    };
    const buffer = await renderPdf(React.createElement(LetterDocument, { d }));
    const pdfPath = await saveFile({ group: "DOCGEN", data: buffer, ext: "pdf", createdBy: s.audit });
    const id = await insertReturningId(db.manager, GeneratedDocument, {
      dossierId: dossier.id, type, templateVersion: "v1-placeholder", pdfPath, generatorUserId: s.userId, ...createAudit(s.audit),
    });
    revalidatePath(`/dossiers/${dossier.id}`);
    return { id, pdfPath };
  });
}

/** Attaches the signed scan of a generated document. */
export async function uploadSignedDocument(generatedDocumentId: number, formData: FormData) {
  return attempt(async () => {
    const s = await requireInternal();
    const db = await getDb();
    const doc = await db.getRepository(GeneratedDocument).findOne({ where: { id: validId(generatedDocumentId, "Documento") } });
    if (!doc || doc.status !== 1) throw new Error("Documento no encontrado.");
    const dossier = await loadDossier(doc.dossierId, true);
    const { data, ext } = await readUpload(formData, ["pdf", "jpg", "png"]);
    const signedFilePath = await saveFile({ group: "DOCGEN", data, ext, createdBy: s.audit });
    await db.getRepository(GeneratedDocument).update({ id: doc.id }, { signedFilePath, signedAt: todayIso(), ...updateAudit(s.audit) });
    revalidatePath(`/dossiers/${dossier.id}`);
    return { signedFilePath };
  });
}
