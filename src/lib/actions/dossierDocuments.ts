export type DocRow = { type: number; label: string; hint?: string; status: number; filePath: string | null; receivedAt: string | null; notes: string | null; autoGenerated: boolean };
export type GeneratedItem = { id: number; type: number; label: string; pdfPath: string | null; signedFilePath: string | null; signedAt: string | null; generatedAt: string; generatedBy: string };
export type GeneralData = {
  registryNumber: string; address: string; district: string; province: string; department: string; legalRepresentative: string;
  companyPhone: string; companyEmail: string; contactName: string; contactPhone: string; contactEmail: string; generalNotes: string;
};
export type DocumentsOverview = {
  documents: DocRow[];
  certificateProgress: { certifiedCount: number; eligibleCount: number };
  fichaProgress: { withCount: number; totalCount: number };
  swornSuggestion: boolean;
  generalData: GeneralData;
  generated: GeneratedItem[];
};

async function loadDossier(id: number, mustBeOpen: boolean): Promise<DossierEntity> {
  const db = await getDb();
  const d = await db.getRepository(Dossier).findOne({ where: { id: validId(id, "Expediente") } });
  if (!d) throw new Error("Expediente no encontrado.");
  if (mustBeOpen && d.status !== DOSSIER_STATUS.OPEN) throw new Error("El expediente no está abierto.");
  return d;
}

function checkType(type: number) {
  if (!DOC_TYPES.some((t) => t.type === type)) throw new Error("Tipo de documento inválido.");
}

/** Everything the "Documentos del expediente" block needs, in one call. */
export async function getDossierDocumentsOverview(dossierId: number): Promise<DocumentsOverview> {
  await requireInternal();
  const dossier = await loadDossier(dossierId, false);
  const db = await getDb();
  const [rows, products, generatedRows] = await Promise.all([
    db.getRepository(DossierDocument).find({ where: { dossierId: dossier.id } }),
    db.getRepository(Product).find({ where: { dossierId: dossier.id, status: 1 } }),
    db.getRepository(GeneratedDocument).find({ where: { dossierId: dossier.id, status: 1 }, order: { id: "DESC" } }),
  ]);
  const productIds = products.map((p) => p.id);
  const [evals, certs] = productIds.length
    ? await Promise.all([
        db.getRepository(Evaluation).find({ where: { productId: In(productIds), status: 1, selectedForCertificate: 1, result: EVAL_RESULT.CONFORME } }),
        db.getRepository(Certificate).find({ where: { productId: In(productIds) } }),
      ])
    : [[], []];
  const eligibleIds = new Set(evals.map((e) => e.productId));
  const names = await internalUserNames(generatedRows.map((g) => g.generatorUserId));
  const s = (v: string | null) => v ?? "";

  return {
    documents: DOC_TYPES.map((t) => {
      const r = rows.find((x) => x.documentType === t.type);
      return { type: t.type, label: t.label, hint: t.hint, status: r?.status ?? DOC_STATUS.PENDING, filePath: r?.filePath ?? null, receivedAt: r?.receivedAt ?? null, notes: r?.notes ?? null, autoGenerated: r?.autoGenerated === 1 };
    }),
    certificateProgress: { eligibleCount: eligibleIds.size, certifiedCount: certs.filter((c) => eligibleIds.has(c.productId)).length },
    fichaProgress: { totalCount: products.length, withCount: products.filter((p) => p.techSheetPath).length },
    swornSuggestion: eligibleIds.size > 0,
    generalData: {
      registryNumber: s(dossier.registryNumber), address: s(dossier.address), district: s(dossier.district), province: s(dossier.province), department: s(dossier.department),
      legalRepresentative: s(dossier.legalRepresentative), companyPhone: s(dossier.companyPhone), companyEmail: s(dossier.companyEmail),
      contactName: s(dossier.contactName), contactPhone: s(dossier.contactPhone), contactEmail: s(dossier.contactEmail), generalNotes: s(dossier.generalNotes),
    },
    generated: generatedRows.map((g) => ({
      id: g.id, type: g.type, label: GENERATED_META[g.type]?.label ?? "Documento", pdfPath: g.pdfPath, signedFilePath: g.signedFilePath, signedAt: g.signedAt,
      generatedAt: g.createdAt, generatedBy: names.get(g.generatorUserId) ?? "—",
    })),
  };
}

/** Create-or-update the checklist row of one document type (rows are created lazily). */
async function upsertRow(dossierId: number, type: number, values: Record<string, unknown>, audit: string) {
  const db = await getDb();
  const repo = db.getRepository(DossierDocument);
  for (let attemptNo = 0; attemptNo < 2; attemptNo++) {
    const existing = await repo.findOne({ where: { dossierId, documentType: type } });
    if (existing) {
      await repo.update({ id: existing.id }, { ...values, ...updateAudit(audit) });
      return;
    }
    try {
      await insertReturningId(db.manager, DossierDocument, { dossierId, documentType: type, ...values, ...createAudit(audit) });
      return;
    } catch (err) {
      if (!isUniqueViolation(err) || attemptNo === 1) throw err; // someone created it at the same time: update instead
    }
  }
}

export async function setDossierDocumentStatus(dossierId: number, type: number, status: number, notes?: string) {
  return attempt(async () => {
    const s = await requireInternal();
    const dossier = await loadDossier(dossierId, true);
    checkType(type);
    if (status !== DOC_STATUS.PENDING && status !== DOC_STATUS.RECEIVED && status !== DOC_STATUS.NOT_APPLICABLE) throw new Error("Estado inválido.");
    const db = await getDb();
    const existing = await db.getRepository(DossierDocument).findOne({ where: { dossierId: dossier.id, documentType: type } });
    // A document with a file (or created automatically) is objectively received: only its notes may change.
    const settled = !!existing && (!!existing.filePath || existing.autoGenerated === 1);
    const finalStatus = settled ? DOC_STATUS.RECEIVED : status;
    await upsertRow(dossier.id, type, {
      status: finalStatus,
      receivedAt: finalStatus === DOC_STATUS.RECEIVED ? existing?.receivedAt ?? todayIso() : null,
      notes: text(notes, "Las notas", 1000),
    }, s.audit);
    revalidatePath(`/dossiers/${dossier.id}`);
  });
}

async function readUpload(formData: FormData, allowed: ("pdf" | "jpg" | "png")[]) {
  const file = formData.get("file");
  if (!(file instanceof File) || file.size === 0) throw new Error("Seleccione un archivo.");
  if (file.size > MAX_UPLOAD_BYTES) throw new Error("El archivo supera 10 MB.");
  const data = Buffer.from(await file.arrayBuffer());
  const real = detectFileType(data); // trust the content, not the name
  if (!real || !allowed.includes(real)) throw new Error("Formato no permitido. Use PDF, JPG o PNG.");
  return { data, ext: real };
}

/** Attaches a file to a checklist document (marks it received). The previous file stays on disk (audit). */
export async function uploadDossierDocument(dossierId: number, type: number, formData: FormData) {
  return attempt(async () => {
    const s = await requireInternal();
    const dossier = await loadDossier(dossierId, true);
    checkType(type);
    if (type === DOC_TYPE.FORM_GCFO0182) throw new Error("El formulario GCFO0182 se genera automáticamente; no se sube.");
    const { data, ext } = await readUpload(formData, ["pdf", "jpg", "png"]);
    const db = await getDb();
    const existing = await db.getRepository(DossierDocument).findOne({ where: { dossierId: dossier.id, documentType: type } });
    const filePath = await saveFile({ group: "EXPDOC", data, ext, createdBy: s.audit });
    await upsertRow(dossier.id, type, { status: DOC_STATUS.RECEIVED, receivedAt: existing?.receivedAt ?? todayIso(), filePath }, s.audit);
    revalidatePath(`/dossiers/${dossier.id}`);
    return { filePath };
  });
}

