import { EntitySchema } from "typeorm";
import { AuditFields, auditColumns } from "./_audit";

// DossierDocument — AQUA_EXPEDIENTE_DOCUMENTO
export interface DossierDocumentEntity extends AuditFields {
  id: number;
  dossierId: number;
  documentType: number;
  filePath: string | null;
  receivedAt: string | null;
  notes: string | null;
  autoGenerated: number;
}

export const DossierDocument = new EntitySchema<DossierDocumentEntity>({
  name: "DossierDocument",
  tableName: "AQUA_EXPEDIENTE_DOCUMENTO",
  columns: {
    id: { primary: true, type: "number", name: "NCODEXPEDIENTEDOCUMENTO" },
    dossierId: { type: "number", precision: 20, name: "NCODEXPEDIENTE" },
    documentType: { type: "number", width: 2, name: "NTIPODOCUMENTO" },
    filePath: { type: "varchar2", length: 500, nullable: true, name: "VARCHIVOURL" },
    receivedAt: { type: "date", nullable: true, name: "DFECRECEPCION" },
    notes: { type: "varchar2", length: 1000, nullable: true, name: "VNOTAS" },
    autoGenerated: { type: "number", width: 1, default: 0, name: "NAUTOGENERADO" },
    ...auditColumns,
  },
  uniques: [
    { name: "UQ_EXPDOC_EXP_TIPO", columns: ["dossierId", "documentType"] },
  ],
});
